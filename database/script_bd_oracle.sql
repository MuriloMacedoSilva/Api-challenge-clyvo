-- Ambiente institucional confirmado: schema RM566462, AL32UTF8 e
-- MAX_STRING_SIZE=STANDARD. Nenhuma credencial e armazenada neste arquivo.
--
-- IMPORTANTE:
-- 1. Execute antes as pre-verificacoes de database/README-oracle.md.
-- 2. Prossiga somente se nenhum objeto ou constraint planejado ja existir.
-- 3. DDL Oracle realiza COMMIT implicito; nao ha rollback atomico do arquivo.
-- 4. O script nao remove, substitui ou altera objetos preexistentes.
-- 5. O script nao cria dados, packages, procedures, functions ou triggers.

SET ECHO ON
SET FEEDBACK ON
SET DEFINE OFF
WHENEVER OSERROR EXIT FAILURE
WHENEVER SQLERROR EXIT SQL.SQLCODE

CREATE TABLE tutor (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR2(200 CHAR) NOT NULL,
    email VARCHAR2(400 CHAR) NOT NULL,
    cpf VARCHAR2(11 CHAR) NOT NULL,
    phone_number VARCHAR2(11 CHAR) NOT NULL,
    password VARCHAR2(11 CHAR) NOT NULL,
    role VARCHAR2(255 CHAR) NOT NULL,
    CONSTRAINT pk_cv_tutor PRIMARY KEY (id)
);

CREATE TABLE veterinarian (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR2(200 CHAR) NOT NULL,
    email VARCHAR2(400 CHAR) NOT NULL,
    cpf VARCHAR2(11 CHAR) NOT NULL,
    phone_number VARCHAR2(11 CHAR) NOT NULL,
    password VARCHAR2(11 CHAR) NOT NULL,
    role VARCHAR2(255 CHAR) NOT NULL,
    crmv_number VARCHAR2(6 CHAR),
    crmv_state VARCHAR2(2 CHAR),
    cnpj VARCHAR2(14 CHAR) NOT NULL,
    CONSTRAINT pk_cv_veterinarian PRIMARY KEY (id)
);

CREATE TABLE tb_device_push_tokens (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    token VARCHAR2(255 CHAR) NOT NULL,
    platform VARCHAR2(20 CHAR) NOT NULL,
    tutor_id NUMBER(19,0),
    veterinarian_id NUMBER(19,0),
    active NUMBER(1,0) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_cv_push_tokens PRIMARY KEY (id),
    CONSTRAINT uk_cv_push_token UNIQUE (token),
    CONSTRAINT ck_cv_push_platform CHECK (platform IN ('ANDROID', 'IOS')),
    CONSTRAINT ck_cv_push_owner CHECK (
        (tutor_id IS NOT NULL AND veterinarian_id IS NULL)
        OR (tutor_id IS NULL AND veterinarian_id IS NOT NULL)
    ),
    CONSTRAINT ck_cv_push_active CHECK (active IN (0, 1)),
    CONSTRAINT fk_cv_push_tutor FOREIGN KEY (tutor_id) REFERENCES tutor (id),
    CONSTRAINT fk_cv_push_vet FOREIGN KEY (veterinarian_id) REFERENCES veterinarian (id)
);

CREATE TABLE animal (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR2(150 CHAR) NOT NULL,
    weight FLOAT(24) NOT NULL,
    height FLOAT(24) NOT NULL,
    age NUMBER(10,0) NOT NULL,
    race VARCHAR2(255 CHAR) NOT NULL,
    species VARCHAR2(255 CHAR) NOT NULL,
    history CLOB,
    tutor_id NUMBER(19,0) NOT NULL,
    CONSTRAINT pk_cv_animal PRIMARY KEY (id),
    CONSTRAINT uk_cv_animal_tutor_name UNIQUE (tutor_id, name),
    CONSTRAINT fk_cv_animal_tutor FOREIGN KEY (tutor_id) REFERENCES tutor (id)
);

CREATE TABLE tb_veterinarian_tutor_links (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    veterinarian_id NUMBER(19,0) NOT NULL,
    tutor_id NUMBER(19,0) NOT NULL,
    status VARCHAR2(255 CHAR) NOT NULL,
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6),
    CONSTRAINT pk_cv_vet_tutor_links PRIMARY KEY (id),
    CONSTRAINT uk_cv_vet_tutor_link UNIQUE (veterinarian_id, tutor_id),
    CONSTRAINT ck_cv_vet_tutor_status CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED')),
    CONSTRAINT fk_cv_link_vet FOREIGN KEY (veterinarian_id) REFERENCES veterinarian (id),
    CONSTRAINT fk_cv_link_tutor FOREIGN KEY (tutor_id) REFERENCES tutor (id)
);

CREATE TABLE tb_appointments (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    animal_id NUMBER(19,0) NOT NULL,
    tutor_id NUMBER(19,0) NOT NULL,
    veterinarian_id NUMBER(19,0) NOT NULL,
    scheduled_at TIMESTAMP(6) NOT NULL,
    reason VARCHAR2(1000 CHAR) NOT NULL,
    status VARCHAR2(255 CHAR) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6),
    CONSTRAINT pk_cv_appointments PRIMARY KEY (id),
    CONSTRAINT ck_cv_appointment_status CHECK (
        status IN ('PENDING', 'CONFIRMED', 'CANCELLED', 'COMPLETED')
    ),
    CONSTRAINT fk_cv_appt_animal FOREIGN KEY (animal_id) REFERENCES animal (id),
    CONSTRAINT fk_cv_appt_tutor FOREIGN KEY (tutor_id) REFERENCES tutor (id),
    CONSTRAINT fk_cv_appt_vet FOREIGN KEY (veterinarian_id) REFERENCES veterinarian (id)
);

CREATE TABLE tb_medical_records (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    animal_id NUMBER(19,0) NOT NULL,
    veterinarian_id NUMBER(19,0) NOT NULL,
    appointment_id NUMBER(19,0) NOT NULL,
    diagnosis VARCHAR2(500 CHAR) NOT NULL,
    description VARCHAR2(4000 CHAR) NOT NULL,
    weight FLOAT(24),
    temperature FLOAT(24),
    observations VARCHAR2(4000 CHAR),
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6),
    CONSTRAINT pk_cv_medical_records PRIMARY KEY (id),
    CONSTRAINT uk_cv_medical_appt UNIQUE (appointment_id),
    CONSTRAINT fk_cv_medical_animal FOREIGN KEY (animal_id) REFERENCES animal (id),
    CONSTRAINT fk_cv_medical_vet FOREIGN KEY (veterinarian_id) REFERENCES veterinarian (id),
    CONSTRAINT fk_cv_medical_appt FOREIGN KEY (appointment_id) REFERENCES tb_appointments (id)
);

CREATE TABLE tb_prescriptions (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    medical_record_id NUMBER(19,0) NOT NULL,
    instructions VARCHAR2(4000 CHAR),
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6),
    CONSTRAINT pk_cv_prescriptions PRIMARY KEY (id),
    CONSTRAINT uk_cv_prescription_record UNIQUE (medical_record_id),
    CONSTRAINT fk_cv_prescription_record FOREIGN KEY (medical_record_id) REFERENCES tb_medical_records (id)
);

CREATE TABLE tb_prescription_items (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    prescription_id NUMBER(19,0) NOT NULL,
    medication_name VARCHAR2(200 CHAR) NOT NULL,
    dosage VARCHAR2(200 CHAR) NOT NULL,
    frequency VARCHAR2(200 CHAR) NOT NULL,
    duration VARCHAR2(200 CHAR) NOT NULL,
    route VARCHAR2(100 CHAR) NOT NULL,
    instructions VARCHAR2(1000 CHAR),
    item_order NUMBER(10,0),
    CONSTRAINT pk_cv_prescription_items PRIMARY KEY (id),
    CONSTRAINT fk_cv_item_prescription FOREIGN KEY (prescription_id) REFERENCES tb_prescriptions (id)
);

CREATE TABLE tb_exams (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    medical_record_id NUMBER(19,0) NOT NULL,
    exam_name VARCHAR2(200 CHAR) NOT NULL,
    exam_type VARCHAR2(200 CHAR),
    status VARCHAR2(255 CHAR) NOT NULL,
    request_date TIMESTAMP(6) NOT NULL,
    result_date TIMESTAMP(6),
    result VARCHAR2(4000 CHAR),
    observations VARCHAR2(4000 CHAR),
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6),
    CONSTRAINT pk_cv_exams PRIMARY KEY (id),
    CONSTRAINT ck_cv_exam_status CHECK (status IN ('REQUESTED', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT fk_cv_exam_record FOREIGN KEY (medical_record_id) REFERENCES tb_medical_records (id)
);

CREATE TABLE tb_vaccinations (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    animal_id NUMBER(19,0) NOT NULL,
    veterinarian_id NUMBER(19,0) NOT NULL,
    vaccine_name VARCHAR2(200 CHAR) NOT NULL,
    application_date DATE NOT NULL,
    next_dose_date DATE,
    batch_number VARCHAR2(100 CHAR),
    manufacturer VARCHAR2(200 CHAR),
    observations VARCHAR2(4000 CHAR),
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6),
    CONSTRAINT pk_cv_vaccinations PRIMARY KEY (id),
    CONSTRAINT fk_cv_vaccine_animal FOREIGN KEY (animal_id) REFERENCES animal (id),
    CONSTRAINT fk_cv_vaccine_vet FOREIGN KEY (veterinarian_id) REFERENCES veterinarian (id)
);

CREATE TABLE tb_notifications (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    message VARCHAR2(255 CHAR) NOT NULL,
    type VARCHAR2(255 CHAR) NOT NULL,
    is_read NUMBER(1,0) NOT NULL,
    created_at TIMESTAMP(6),
    tutor_id NUMBER(19,0),
    veterinarian_id NUMBER(19,0),
    link_id NUMBER(19,0),
    CONSTRAINT pk_cv_notifications PRIMARY KEY (id),
    CONSTRAINT ck_cv_notification_read CHECK (is_read IN (0, 1)),
    CONSTRAINT ck_cv_notification_type CHECK (type IN (
        'LINK_REQUEST_SENT', 'LINK_REQUEST_RECEIVED', 'LINK_REQUEST_ACCEPTED',
        'LINK_REQUEST_REJECTED', 'APPOINTMENT_REQUESTED', 'APPOINTMENT_CONFIRMED',
        'APPOINTMENT_CANCELLED', 'APPOINTMENT_COMPLETED', 'MEDICAL_RECORD_CREATED',
        'PRESCRIPTION_CREATED', 'EXAM_REQUESTED', 'EXAM_RESULT_AVAILABLE',
        'EXAM_CANCELLED', 'VACCINATION_REGISTERED'
    )),
    CONSTRAINT fk_cv_notification_tutor FOREIGN KEY (tutor_id) REFERENCES tutor (id),
    CONSTRAINT fk_cv_notification_vet FOREIGN KEY (veterinarian_id) REFERENCES veterinarian (id),
    CONSTRAINT fk_cv_notification_link FOREIGN KEY (link_id) REFERENCES tb_veterinarian_tutor_links (id)
);

CREATE TABLE tb_conversations (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    tutor_id NUMBER(19,0) NOT NULL,
    veterinarian_id NUMBER(19,0) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_cv_conversations PRIMARY KEY (id),
    CONSTRAINT uk_cv_conversation_pair UNIQUE (tutor_id, veterinarian_id),
    CONSTRAINT fk_cv_conversation_tutor FOREIGN KEY (tutor_id) REFERENCES tutor (id),
    CONSTRAINT fk_cv_conversation_vet FOREIGN KEY (veterinarian_id) REFERENCES veterinarian (id)
);

CREATE TABLE tb_messages (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    conversation_id NUMBER(19,0) NOT NULL,
    sender_type VARCHAR2(20 CHAR) NOT NULL,
    content VARCHAR2(2000 CHAR) NOT NULL,
    is_read NUMBER(1,0) NOT NULL,
    sent_at TIMESTAMP(6) NOT NULL,
    read_at TIMESTAMP(6),
    CONSTRAINT pk_cv_messages PRIMARY KEY (id),
    CONSTRAINT ck_cv_message_sender CHECK (sender_type IN ('TUTOR', 'VETERINARIAN')),
    CONSTRAINT ck_cv_message_read CHECK (is_read IN (0, 1)),
    CONSTRAINT fk_cv_message_conversation FOREIGN KEY (conversation_id) REFERENCES tb_conversations (id)
);

-- Oracle cria indices para PKs e constraints UNIQUE, mas nao para FKs.
CREATE INDEX ix_cv_link_tutor_status
    ON tb_veterinarian_tutor_links (tutor_id, status);
CREATE INDEX ix_cv_link_vet_status
    ON tb_veterinarian_tutor_links (veterinarian_id, status);
CREATE INDEX ix_cv_appt_tutor_sched
    ON tb_appointments (tutor_id, scheduled_at);
CREATE INDEX ix_cv_appt_vet_status_sched
    ON tb_appointments (veterinarian_id, status, scheduled_at);
CREATE INDEX ix_cv_medical_animal_created
    ON tb_medical_records (animal_id, created_at DESC);
CREATE INDEX ix_cv_item_order
    ON tb_prescription_items (prescription_id, item_order);
CREATE INDEX ix_cv_exam_record_request
    ON tb_exams (medical_record_id, request_date DESC);
CREATE INDEX ix_cv_vaccine_animal_apply
    ON tb_vaccinations (animal_id, application_date DESC);
CREATE INDEX ix_cv_vaccine_animal_next
    ON tb_vaccinations (animal_id, next_dose_date);
CREATE INDEX ix_cv_notif_tutor_created
    ON tb_notifications (tutor_id, created_at DESC);
CREATE INDEX ix_cv_notif_vet_created
    ON tb_notifications (veterinarian_id, created_at DESC);
CREATE INDEX ix_cv_push_tutor_active
    ON tb_device_push_tokens (tutor_id, active);
CREATE INDEX ix_cv_push_vet_active
    ON tb_device_push_tokens (veterinarian_id, active);
CREATE INDEX ix_cv_conv_tutor_updated
    ON tb_conversations (tutor_id, updated_at DESC);
CREATE INDEX ix_cv_conv_vet_updated
    ON tb_conversations (veterinarian_id, updated_at DESC);
CREATE INDEX ix_cv_msg_conv_sent
    ON tb_messages (conversation_id, sent_at, id);

-- Oracle 19c nao oferece o indice parcial PostgreSQL "WHERE is_read = false".
-- IS_READ entra na chave para suportar a consulta de mensagens nao lidas.
CREATE INDEX ix_cv_msg_unread
    ON tb_messages (conversation_id, sender_type, is_read, id);

