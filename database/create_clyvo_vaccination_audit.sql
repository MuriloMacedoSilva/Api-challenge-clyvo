CREATE TABLE tb_clyvo_vaccination_audit (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    vaccination_id NUMBER(19,0) NOT NULL,
    operation_type VARCHAR2(6 CHAR) NOT NULL,
    event_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    old_animal_id NUMBER(19,0),
    new_animal_id NUMBER(19,0),
    old_veterinarian_id NUMBER(19,0),
    new_veterinarian_id NUMBER(19,0),
    old_vaccine_name VARCHAR2(200 CHAR),
    new_vaccine_name VARCHAR2(200 CHAR),
    old_application_date DATE,
    new_application_date DATE,
    old_next_dose_date DATE,
    new_next_dose_date DATE,
    old_batch_number VARCHAR2(100 CHAR),
    new_batch_number VARCHAR2(100 CHAR),
    old_manufacturer VARCHAR2(200 CHAR),
    new_manufacturer VARCHAR2(200 CHAR),
    observations_changed NUMBER(1,0) DEFAULT 0 NOT NULL,
    database_user VARCHAR2(128 BYTE) NOT NULL,
    client_identifier VARCHAR2(64 BYTE),
    CONSTRAINT pk_cv_vaccination_audit PRIMARY KEY (id),
    CONSTRAINT ck_cv_vacc_aud_operation CHECK (
        operation_type IN ('INSERT', 'UPDATE', 'DELETE')
    ),
    CONSTRAINT ck_cv_vacc_aud_vacc_id CHECK (
        vaccination_id > 0 AND vaccination_id = TRUNC(vaccination_id)
    ),
    CONSTRAINT ck_cv_vacc_aud_obs_changed CHECK (
        observations_changed IN (0, 1)
    ),
    CONSTRAINT ck_cv_vacc_aud_snapshot CHECK (
        (
            operation_type = 'INSERT'
            AND old_animal_id IS NULL
            AND old_veterinarian_id IS NULL
            AND old_vaccine_name IS NULL
            AND old_application_date IS NULL
            AND old_next_dose_date IS NULL
            AND old_batch_number IS NULL
            AND old_manufacturer IS NULL
            AND new_animal_id IS NOT NULL
            AND new_veterinarian_id IS NOT NULL
            AND new_vaccine_name IS NOT NULL
            AND new_application_date IS NOT NULL
            AND observations_changed = 0
        )
        OR (
            operation_type = 'UPDATE'
            AND old_animal_id IS NOT NULL
            AND new_animal_id IS NOT NULL
            AND old_veterinarian_id IS NOT NULL
            AND new_veterinarian_id IS NOT NULL
            AND old_vaccine_name IS NOT NULL
            AND new_vaccine_name IS NOT NULL
            AND old_application_date IS NOT NULL
            AND new_application_date IS NOT NULL
        )
        OR (
            operation_type = 'DELETE'
            AND old_animal_id IS NOT NULL
            AND old_veterinarian_id IS NOT NULL
            AND old_vaccine_name IS NOT NULL
            AND old_application_date IS NOT NULL
            AND new_animal_id IS NULL
            AND new_veterinarian_id IS NULL
            AND new_vaccine_name IS NULL
            AND new_application_date IS NULL
            AND new_next_dose_date IS NULL
            AND new_batch_number IS NULL
            AND new_manufacturer IS NULL
            AND observations_changed = 0
        )
    )
);

CREATE INDEX ix_cv_vacc_aud_vacc_event
    ON tb_clyvo_vaccination_audit (vaccination_id, event_at, id);

COMMENT ON TABLE tb_clyvo_vaccination_audit IS
    'Auditoria transacional de INSERT, UPDATE e DELETE em TB_VACCINATIONS.';
COMMENT ON COLUMN tb_clyvo_vaccination_audit.vaccination_id IS
    'ID historico da vacinacao; sem FK para preservar eventos apos DELETE.';
COMMENT ON COLUMN tb_clyvo_vaccination_audit.event_at IS
    'Instante Oracle do evento, com fuso do banco preservado.';
COMMENT ON COLUMN tb_clyvo_vaccination_audit.observations_changed IS
    'Indica mudanca de observacoes sem armazenar seu conteudo clinico.';
COMMENT ON COLUMN tb_clyvo_vaccination_audit.database_user IS
    'SESSION_USER tecnico; nao identifica Tutor ou Veterinario da aplicacao.';
COMMENT ON COLUMN tb_clyvo_vaccination_audit.client_identifier IS
    'CLIENT_IDENTIFIER opcional; a aplicacao atual nao garante seu preenchimento.';

