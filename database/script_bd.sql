COMMENT ON COLUMN tb_appointments.scheduled_at IS 'Data e horario local agendados para a consulta.';
COMMENT ON COLUMN tb_appointments.status IS 'Estado do ciclo de vida da consulta.';

COMMENT ON TABLE tb_medical_records IS 'Prontuarios clinicos, no maximo um por consulta.';
COMMENT ON COLUMN tb_medical_records.appointment_id IS 'Consulta concluida que originou o prontuario.';
COMMENT ON COLUMN tb_medical_records.description IS 'Descricao clinica detalhada do atendimento.';

