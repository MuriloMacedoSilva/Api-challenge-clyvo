COMMENT ON COLUMN tb_messages.sender_type IS 'Papel do remetente: TUTOR ou VETERINARIAN.';
COMMENT ON COLUMN tb_messages.read_at IS 'Instante em que o destinatario marcou a mensagem como lida.';

COMMIT;
